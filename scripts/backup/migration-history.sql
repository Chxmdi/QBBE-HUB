-- Writes the migration history (the supabase_migrations schema), in one
-- psql call, as two files a restore runs after data.sql:
--
--   psql "$BACKUP_DB_URL" -X -q -v ON_ERROR_STOP=1 \
--     -v schema_file=history_schema.sql -v data_file=history_data.sql \
--     -f scripts/backup/migration-history.sql
--
-- history_schema.sql  the schema and each table's definition (columns,
--                     defaults, constraints, indexes), as pg_dump writes them
-- history_data.sql    each table's rows as COPY ... FROM stdin blocks, in the
--                     same text format pg_dump uses
--
-- With these, the next deploy's `supabase db push` against a restored
-- project knows which migrations it already has. They used to be two more
-- pg_dump runs a night; each pg_dump run reads about 2 MB of catalog from
-- Supabase on top of the data, and this reads only the rows (Supabase's
-- free plan allows 5 GB of outgoing traffic a month; runbook, "Supabase
-- traffic"). Every table in the schema is written, whatever the CLI version
-- created.

\set ON_ERROR_STOP on
\pset format unaligned
\pset tuples_only on
\pset footer off
set search_path = '';

\o :schema_file
select '-- history_schema.sql: generated by scripts/backup/migration-history.sql';
select 'CREATE SCHEMA IF NOT EXISTS "supabase_migrations";';
select format(E'\nCREATE TABLE IF NOT EXISTS %I.%I (\n%s\n);', n.nspname, c.relname,
              string_agg(format('    %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                                coalesce(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), ''),
                                case when a.attnotnull then ' NOT NULL' else '' end),
                         E',\n' order by a.attnum))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
 where n.nspname = 'supabase_migrations' and c.relkind = 'r'
 group by n.nspname, c.relname
 order by c.relname;
select format('ALTER TABLE ONLY %I.%I ADD CONSTRAINT %I %s;', n.nspname, c.relname, k.conname, pg_get_constraintdef(k.oid))
  from pg_constraint k
  join pg_class c on c.oid = k.conrelid
  join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'supabase_migrations' and c.relkind = 'r'
 order by c.relname, k.contype = 'f', k.conname;
select pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i
  join pg_class c on c.oid = i.indrelid
  join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'supabase_migrations'
   and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
 order by 1;

\o :data_file
select '-- history_data.sql: generated by scripts/backup/migration-history.sql';
-- Per table: the COPY line, the rows (COPY ... TO STDOUT goes to this
-- file), and the end-of-data line.
select format('select %L', format('COPY %s.%s (%s) FROM stdin;',
                                  '"' || replace(n.nspname, '"', '""') || '"',
                                  '"' || replace(c.relname, '"', '""') || '"',
                                  string_agg('"' || replace(a.attname, '"', '""') || '"', ', ' order by a.attnum))),
       format('COPY (select %s from %I.%I order by 1) TO STDOUT',
              string_agg(format('%I', a.attname), ', ' order by a.attnum), n.nspname, c.relname),
       $$select '\.'$$
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped and a.attgenerated = ''
 where n.nspname = 'supabase_migrations' and c.relkind = 'r'
 group by n.nspname, c.relname
 order by c.relname
\gexec
\o
