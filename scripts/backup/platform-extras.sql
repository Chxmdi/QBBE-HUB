-- Prints platform.sql: the parts of this database that Supabase's three-part
-- dump (roles, schema, data) leaves out, as statements a restore can run.
--
--   psql "$BACKUP_DB_URL" -X -q -v ON_ERROR_STOP=1 -f scripts/backup/platform-extras.sql > platform.sql
--
-- The schema dump skips the auth and storage schemas, because the platform
-- owns them, and the data dump skips extension tables. That loses four
-- things this app relies on (supabase/migrations created them all):
--
--   1. the row-level security policies on storage.objects that decide who can
--      read and upload documents, receipts and form files;
--   2. the app's triggers on auth and storage tables (new sign-ups getting
--      their membership, registered files staying immutable);
--   3. the pgmq queues the background jobs use (their tables live in the
--      pgmq schema; messages waiting in them are not kept);
--   4. the pg_cron schedule that runs the background jobs. Every job is
--      restored paused (active = false), whatever it was in the backup, so
--      nothing runs in a restored project before its job runner is wired
--      (and a drill's scratch project never runs them at all), and the
--      drill's row checks stay exact. The last line, a comment starting
--      "-- start-schedule: ", is the statement that starts again the jobs
--      that were running in the backup; restore-drill.sh prints it, and the
--      runbook's restore runs it once the job runner is wired.
--
-- Supabase documents (1) and (2) as "restore them separately"
-- (docs/runbooks/backup-recovery.md). Names are written fully qualified
-- (search_path is empty while printing), so the output runs anywhere.

\set ON_ERROR_STOP on
\pset format unaligned
\pset tuples_only on
\pset footer off
set search_path = '';

select '-- platform.sql: generated by scripts/backup/platform-extras.sql at '
       || to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"');

-- 1. Policies on auth and storage tables. Dropped first so the file can be
-- applied to a project that already has some of them.
select format('DROP POLICY IF EXISTS %I ON %I.%I;', p.policyname, p.schemaname, p.tablename)
       || E'\n'
       || format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
                 p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
                 (select string_agg(quote_ident(r), ', ') from unnest(p.roles) as r),
                 case when p.qual is not null then E'\n  USING (' || p.qual || ')' else '' end,
                 case when p.with_check is not null then E'\n  WITH CHECK (' || p.with_check || ')' else '' end)
  from pg_policies p
 where p.schemaname in ('auth', 'storage')
 order by p.schemaname, p.tablename, p.policyname;

-- 2. The app's triggers on auth and storage tables: those whose function is
-- not the platform's own (the platform's live in auth and storage).
select regexp_replace(pg_get_triggerdef(t.oid), '^CREATE (CONSTRAINT )?TRIGGER', 'CREATE OR REPLACE \1TRIGGER') || ';'
       || case t.tgenabled
            when 'D' then format(E'\nALTER TABLE %I.%I DISABLE TRIGGER %I;', n.nspname, c.relname, t.tgname)
            when 'R' then format(E'\nALTER TABLE %I.%I ENABLE REPLICA TRIGGER %I;', n.nspname, c.relname, t.tgname)
            when 'A' then format(E'\nALTER TABLE %I.%I ENABLE ALWAYS TRIGGER %I;', n.nspname, c.relname, t.tgname)
            else ''
          end
  from pg_trigger t
  join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_proc f on f.oid = t.tgfoid
  join pg_namespace fn on fn.oid = f.pronamespace
 where not t.tgisinternal
   and t.tgconstraint = 0
   and n.nspname in ('auth', 'storage')
   and fn.nspname not in ('auth', 'storage')
 order by n.nspname, c.relname, t.tgname;

-- 3. Queues. pgmq.create is idempotent; the messages themselves are not kept.
select to_regclass('pgmq.meta') is not null as has_pgmq \gset
\if :has_pgmq
select format('SELECT pgmq.%s(%L);', case when m.is_unlogged then 'create_unlogged' else 'create' end, m.queue_name)
  from pgmq.meta m
 order by m.queue_name;
\endif

-- 4. The schedule, every job paused. cron.schedule with a job name
-- replaces a job of that name; both statements run in the restore's one
-- transaction, so pg_cron never sees the job active.
select to_regclass('cron.job') is not null as has_cron \gset
\if :has_cron
select format('SELECT cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command)
       || format(E'\nSELECT cron.alter_job((SELECT jobid FROM cron.job WHERE jobname = %L), active := false);', j.jobname)
  from cron.job j
 where j.jobname is not null
 order by j.jobname;
-- The jobs that were running in the backup, as one statement to start them
-- again (a comment here: nothing runs it during the restore). A name with a
-- line break could end the comment, so such a job is left out of it.
select '-- start-schedule: '
       || format('SELECT cron.alter_job(jobid, active := true) FROM cron.job WHERE jobname IN (%s);',
                 string_agg(quote_literal(j.jobname), ', ' order by j.jobname))
  from cron.job j
 where j.jobname is not null and j.active and j.jobname !~ E'[\\r\\n]'
having count(*) > 0;
\endif
