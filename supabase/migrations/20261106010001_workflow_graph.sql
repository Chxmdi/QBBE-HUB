-- ---------------------------------------------------------------------------
-- app.can_as: the access check, answered for a named person
-- ---------------------------------------------------------------------------

-- p_assurance is the sign-in level to ask at. Owners and admins need the
-- two-step level (aal2) for anything but reading. aal2 is only used when the
-- person has a live verified second factor (as app.is_org_admin requires);
-- otherwise the question is asked at aal1. So it never lends someone a level
-- they could not reach themselves.
-- Workflows ask at aal2: only an admin in a two-step session can save one.
create or replace function app.can_as(
  p_user uuid,
  p_object uuid,
  p_capability text,
  p_assurance text default 'aal1'
)
returns boolean
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_claims text := current_setting('request.jwt.claims', true);
  v_sub text := current_setting('request.jwt.claim.sub', true);
  v_role text := current_setting('request.jwt.claim.role', true);
  v_result boolean := false;
  v_assurance text := p_assurance;
begin
  if p_user is null or p_object is null or p_assurance is null
     or p_assurance not in ('aal1', 'aal2') then
    return false;
  end if;
  if v_assurance = 'aal2' and not exists (
    select 1 from auth.mfa_factors f
    where f.user_id = p_user and f.factor_type = 'totp' and f.status = 'verified'
  ) then
    v_assurance := 'aal1';
  end if;

  perform set_config('request.jwt.claims',
    json_build_object('sub', p_user::text, 'role', 'authenticated', 'aal', v_assurance)::text, true);
  perform set_config('request.jwt.claim.sub', p_user::text, true);
  perform set_config('request.jwt.claim.role', 'authenticated', true);
  begin
    v_result := coalesce(app.can(p_object, p_capability), false);
  exception when others then
    v_result := false;
  end;
  perform set_config('request.jwt.claims', coalesce(v_claims, ''), true);
  perform set_config('request.jwt.claim.sub', coalesce(v_sub, ''), true);
  perform set_config('request.jwt.claim.role', coalesce(v_role, ''), true);
  return v_result;
end;
$$;

create or replace function public.can_as(
  p_user uuid,
  p_object uuid,
  p_capability text,
  p_assurance text default 'aal1'
)
returns boolean
language sql volatile security definer
set search_path = ''
as $$
  select app.can_as(p_user, p_object, p_capability, p_assurance);
$$;

revoke all on function app.can_as(uuid, uuid, text, text) from public, anon, authenticated;
revoke all on function public.can_as(uuid, uuid, text, text) from public, anon, authenticated;
grant execute on function app.can_as(uuid, uuid, text, text) to service_role;
grant execute on function public.can_as(uuid, uuid, text, text) to service_role;

comment on function app.can_as(uuid, uuid, text, text) is
  'app.can for a named person at a given sign-in level, for the workflow runner and API tokens. Service role only.';

-- ---------------------------------------------------------------------------
-- The runner job: reads new events and runs matching graph workflows.
-- ---------------------------------------------------------------------------

insert into public.job_definition (name, description, schedule, queue, enabled, batch_size, max_attempts)
values
  ('workflow-events',
   'Runs step-graph workflows for new events. Does nothing while wos_workflows_v2 is off.',
   '* * * * *', null, true, 100, 3)
on conflict (name) do update
  set description = excluded.description,
      schedule = excluded.schedule;

do $$
declare
  j record;
begin
  for j in select name, schedule from public.job_definition where name = 'workflow-events'
  loop
    perform cron.unschedule(j.name)
      where exists (select 1 from cron.job c where c.jobname = j.name);
    perform cron.schedule(j.name, j.schedule,
      format('select app.dispatch_job(%L)', j.name));
  end loop;
end;
$$;
